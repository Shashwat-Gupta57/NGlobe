"""Trust-store handling for the mitmproxy CA certificate (Windows).

Installs into the *current user's* Root store: no admin rights or UAC needed,
Windows shows its own "install this certificate?" confirmation, and Chrome/Edge
trust it. Detection matches by SHA-1 thumbprint, so a stale CA from another
mitmproxy install is not mistaken for ours.
"""

from __future__ import annotations

import base64
import hashlib
import platform
import subprocess
from pathlib import Path
from typing import Optional

from nglobe.utils.logging import get_logger

logger = get_logger(__name__)

_NO_WINDOW = getattr(subprocess, "CREATE_NO_WINDOW", 0)


def cert_path(cert_dir: str) -> Path:
    """Public CA certificate (no private key) generated by mitmproxy in its confdir."""
    return Path(cert_dir).expanduser() / "mitmproxy-ca-cert.pem"


def thumbprint(pem_path: Path) -> Optional[str]:
    try:
        body = "".join(
            line for line in pem_path.read_text().splitlines() if line and not line.startswith("-----")
        )
        return hashlib.sha1(base64.b64decode(body)).hexdigest()
    except (OSError, ValueError):
        return None


class CertInstaller:
    @staticmethod
    def is_installed(pem_path: Path) -> bool:
        if platform.system() != "Windows":
            return False
        thumb = thumbprint(pem_path)
        if thumb is None:
            return False
        for scope in (["-user"], []):  # current-user store, then machine store
            result = subprocess.run(
                ["certutil", *scope, "-store", "Root", thumb],
                capture_output=True, creationflags=_NO_WINDOW,
            )
            if result.returncode == 0:
                return True
        return False

    @staticmethod
    def install(pem_path: Path) -> bool:
        """Blocks until the user answers the Windows confirmation dialog."""
        if platform.system() != "Windows":
            return False
        if not pem_path.exists():
            logger.error("cert_install_failed", error="certificate not generated yet", path=str(pem_path))
            return False
        try:
            subprocess.run(
                ["certutil", "-user", "-addstore", "Root", str(pem_path)],
                capture_output=True, creationflags=_NO_WINDOW,
            )
        except OSError as e:
            logger.error("cert_install_failed", error=str(e))
            return False
        installed = CertInstaller.is_installed(pem_path)
        logger.info("cert_install_result", installed=installed)
        return installed
